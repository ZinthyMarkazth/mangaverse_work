-- MangaVerse repair / setup SQL
-- Run in Supabase Dashboard > SQL Editor as project owner.
-- This script keeps existing manga/chapters and aligns the app with storage-backed images.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null default '',
  role text not null default 'user',
  created_at timestamptz not null default now()
);
alter table public.profiles add column if not exists role text not null default 'user';
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check (role in ('user','admin'));

create table if not exists public.manga (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null default '',
  description text not null default '',
  category text not null default '',
  latest_chapter numeric(8,2) not null default 0,
  status text not null default 'ongoing',
  cover_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.manga add column if not exists author text not null default '';
alter table public.manga add column if not exists description text not null default '';
alter table public.manga add column if not exists category text not null default '';
alter table public.manga add column if not exists latest_chapter numeric(8,2) not null default 0;
alter table public.manga add column if not exists status text not null default 'ongoing';
alter table public.manga add column if not exists cover_path text;
alter table public.manga add column if not exists created_at timestamptz not null default now();
alter table public.manga add column if not exists updated_at timestamptz not null default now();

-- Convert old Thai status values before adding the strict constraint.
update public.manga set status = case
  when lower(coalesce(status,'')) in ('completed','จบแล้ว','complete') then 'completed'
  when lower(coalesce(status,'')) in ('hiatus','พักการเขียน','พัก','หยุดพัก') then 'hiatus'
  else 'ongoing'
end;
alter table public.manga drop constraint if exists manga_status_check;
alter table public.manga add constraint manga_status_check
  check (status in ('ongoing','completed','hiatus'));

create table if not exists public.chapters (
  id bigint generated by default as identity primary key,
  manga_id bigint not null references public.manga(id) on delete cascade,
  chapter_number numeric(8,2) not null,
  title text not null default '',
  created_at timestamptz not null default now(),
  unique (manga_id, chapter_number)
);
create table if not exists public.chapter_images (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references public.chapters(id) on delete cascade,
  image_path text not null,
  image_order integer not null check (image_order > 0),
  unique (chapter_id, image_order)
);


create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'username', ''), 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create index if not exists chapters_manga_number_idx on public.chapters(manga_id, chapter_number);
alter table public.profiles enable row level security;
alter table public.manga enable row level security;
alter table public.chapters enable row level security;
alter table public.chapter_images enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

drop policy if exists "Read own profile" on public.profiles;
create policy "Read own profile" on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "Read manga catalog" on public.manga;
create policy "Read manga catalog" on public.manga for select to anon, authenticated using (true);
drop policy if exists "Admin inserts manga" on public.manga;
create policy "Admin inserts manga" on public.manga for insert to authenticated with check ((select public.is_admin()));
drop policy if exists "Admin updates manga" on public.manga;
create policy "Admin updates manga" on public.manga for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Admin deletes manga" on public.manga;
create policy "Admin deletes manga" on public.manga for delete to authenticated using ((select public.is_admin()));

drop policy if exists "Read chapters" on public.chapters;
create policy "Read chapters" on public.chapters for select to anon, authenticated using (true);
drop policy if exists "Admin manages chapters" on public.chapters;
create policy "Admin manages chapters" on public.chapters for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Read chapter images" on public.chapter_images;
create policy "Read chapter images" on public.chapter_images for select to anon, authenticated using (true);
drop policy if exists "Admin manages chapter images" on public.chapter_images;
create policy "Admin manages chapter images" on public.chapter_images for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('manga-covers','manga-covers',true,5242880,array['image/jpeg','image/png','image/webp']),
  ('manga-pages','manga-pages',true,10485760,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public read manga images" on storage.objects;
create policy "Public read manga images" on storage.objects for select to anon, authenticated
using (bucket_id in ('manga-covers','manga-pages'));
drop policy if exists "Admin upload manga images" on storage.objects;
create policy "Admin upload manga images" on storage.objects for insert to authenticated
with check (bucket_id in ('manga-covers','manga-pages') and (select public.is_admin()));
drop policy if exists "Admin update manga images" on storage.objects;
create policy "Admin update manga images" on storage.objects for update to authenticated
using (bucket_id in ('manga-covers','manga-pages') and (select public.is_admin()))
with check (bucket_id in ('manga-covers','manga-pages') and (select public.is_admin()));
drop policy if exists "Admin delete manga images" on storage.objects;
create policy "Admin delete manga images" on storage.objects for delete to authenticated
using (bucket_id in ('manga-covers','manga-pages') and (select public.is_admin()));

