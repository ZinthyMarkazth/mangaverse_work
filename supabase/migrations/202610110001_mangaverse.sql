-- MangaVerse Supabase schema
-- Run in Supabase Dashboard > SQL Editor on a fresh project.
-- This migration intentionally creates no demo manga records.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.manga (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null default '',
  description text not null default '',
  category text not null default '',
  latest_chapter numeric(8,2) not null default 0,
  status text not null default 'ongoing' check (status in ('ongoing', 'completed', 'hiatus')),
  cover_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chapters (
  id bigint generated by default as identity primary key,
  manga_id bigint not null references public.manga(id) on delete cascade,
  chapter_number numeric(8,2) not null,
  title text not null default '',
  created_at timestamptz not null default now(),
  unique (manga_id, chapter_number)
);

create table if not exists public.chapter_images (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references public.chapters(id) on delete cascade,
  image_path text not null,
  image_order integer not null check (image_order > 0),
  unique (chapter_id, image_order)
);

create table if not exists public.bookshelf (
  user_id uuid not null references public.profiles(id) on delete cascade,
  manga_id bigint not null references public.manga(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (user_id, manga_id)
);

create table if not exists public.reading_progress (
  user_id uuid not null references public.profiles(id) on delete cascade,
  manga_id bigint not null references public.manga(id) on delete cascade,
  chapter_id bigint references public.chapters(id) on delete set null,
  read_at timestamptz not null default now(),
  primary key (user_id, manga_id)
);

create table if not exists public.custom_categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create table if not exists public.custom_category_manga (
  category_id bigint not null references public.custom_categories(id) on delete cascade,
  manga_id bigint not null references public.manga(id) on delete cascade,
  primary key (category_id, manga_id)
);

create index if not exists chapters_manga_number_idx
  on public.chapters (manga_id, chapter_number);
create index if not exists reading_progress_user_idx
  on public.reading_progress (user_id, read_at desc);
create index if not exists custom_categories_user_idx
  on public.custom_categories (user_id);

-- A profile is created on signup. Role is always 'user' by default.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, username, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'username', ''),
    'user'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- SECURITY DEFINER is used only for a read-only role check.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

