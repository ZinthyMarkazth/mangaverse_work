drop policy if exists "Read own profile" on public.profiles;
create policy "Read own profile" on public.profiles for select to authenticated
using (id = (select auth.uid()));

drop policy if exists "Read manga catalog" on public.manga;
create policy "Read manga catalog" on public.manga for select to anon, authenticated using (true);
drop policy if exists "Admin inserts manga" on public.manga;
create policy "Admin inserts manga" on public.manga for insert to authenticated
with check ((select public.is_admin()));
drop policy if exists "Admin updates manga" on public.manga;
create policy "Admin updates manga" on public.manga for update to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Admin deletes manga" on public.manga;
create policy "Admin deletes manga" on public.manga for delete to authenticated
using ((select public.is_admin()));

drop policy if exists "Read chapters" on public.chapters;
create policy "Read chapters" on public.chapters for select to anon, authenticated using (true);
drop policy if exists "Admin manages chapters" on public.chapters;
create policy "Admin manages chapters" on public.chapters for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Read chapter images" on public.chapter_images;
create policy "Read chapter images" on public.chapter_images for select to anon, authenticated using (true);
drop policy if exists "Admin manages chapter images" on public.chapter_images;
create policy "Admin manages chapter images" on public.chapter_images for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Manage own bookshelf" on public.bookshelf;
create policy "Manage own bookshelf" on public.bookshelf for all to authenticated
using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists "Manage own reading progress" on public.reading_progress;
create policy "Manage own reading progress" on public.reading_progress for all to authenticated
using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists "Manage own categories" on public.custom_categories;
create policy "Manage own categories" on public.custom_categories for all to authenticated
using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists "Read own category manga" on public.custom_category_manga;
create policy "Read own category manga" on public.custom_category_manga for select to authenticated
using (exists (select 1 from public.custom_categories c
  where c.id = category_id and c.user_id = (select auth.uid())));
drop policy if exists "Manage manga in own categories" on public.custom_category_manga;
create policy "Manage manga in own categories" on public.custom_category_manga for all to authenticated
using (exists (select 1 from public.custom_categories c
  where c.id = category_id and c.user_id = (select auth.uid())))
with check (exists (select 1 from public.custom_categories c
  where c.id = category_id and c.user_id = (select auth.uid())));

-- Storage buckets. Public reads are suitable only if all manga images are intended to be public.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('manga-covers', 'manga-covers', true, 5242880, array['image/jpeg','image/png','image/webp']),
  ('manga-pages', 'manga-pages', true, 10485760, array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

drop policy if exists "Public read manga images" on storage.objects;
create policy "Public read manga images" on storage.objects for select
to anon, authenticated using (bucket_id in ('manga-covers','manga-pages'));
drop policy if exists "Admin upload manga images" on storage.objects;
create policy "Admin upload manga images" on storage.objects for insert
to authenticated with check (
  bucket_id in ('manga-covers','manga-pages') and (select public.is_admin())
);
drop policy if exists "Admin update manga images" on storage.objects;
create policy "Admin update manga images" on storage.objects for update
to authenticated using (
  bucket_id in ('manga-covers','manga-pages') and (select public.is_admin())
) with check (
  bucket_id in ('manga-covers','manga-pages') and (select public.is_admin())
);
drop policy if exists "Admin delete manga images" on storage.objects;
create policy "Admin delete manga images" on storage.objects for delete
to authenticated using (
  bucket_id in ('manga-covers','manga-pages') and (select public.is_admin())
);
